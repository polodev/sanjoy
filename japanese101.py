def romaji(text):
    """Hepburn-style romaji from hiragana: digraphs, small っ, ん; standalone は/を as particles."""
    out, i, geminate = [], 0, False
    for tok in text.split(" "):
        tok = tok.strip(PUNCT)
        if not tok:
            continue
        if tok in PARTICLES:
            out.append(PARTICLES[tok])
            continue
        if tok in WORD_ROMAJI:
            out.append(WORD_ROMAJI[tok])
            continue
        r, i, geminate = "", 0, False
        while i < len(tok):
            c = tok[i]
            if c == "っ":
                geminate = True
                i += 1
                continue
            if i + 1 < len(tok) and tok[i + 1] in SMALL:
                base = K[c][0]
                part = (base[:-1] if base in ("shi", "chi", "ji") else base[:-1] + "y") + SMALL[tok[i + 1]][1]
                i += 2
            else:
                part = K[c][0]
                i += 1
            if geminate:
                part = ("t" + part) if part.startswith("ch") else part[0] + part
                geminate = False
            r += part
        out.append(r)
    return " ".join(out)


def allowed_chars(letters, day):
    small = {"っ", "ゃ", "ゅ", "ょ"} if day >= 10 else set()   # small kana are taught on Day 10
    return set(letters) | set(PUNCT) | {" "} | small


